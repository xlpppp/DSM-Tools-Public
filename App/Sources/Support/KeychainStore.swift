import Foundation
import Security

/// Secrets (passwords, device tokens) live only in the Keychain, never in files or logs.
enum KeychainStore {
    private static let service = "com.xlpppp.nashelper"

    static func set(_ value: String?, for key: String) {
        let base: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: key,
        ]
        SecItemDelete(base as CFDictionary)
        guard let value, !value.isEmpty else { return }
        var item = base
        item[kSecValueData as String] = Data(value.utf8)
        item[kSecAttrAccessible as String] = kSecAttrAccessibleAfterFirstUnlockThisDeviceOnly
        SecItemAdd(item as CFDictionary, nil)
    }

    static func get(_ key: String) -> String? {
        let query: [String: Any] = [
            kSecClass as String: kSecClassGenericPassword,
            kSecAttrService as String: service,
            kSecAttrAccount as String: key,
            kSecReturnData as String: true,
            kSecMatchLimit as String: kSecMatchLimitOne,
        ]
        var out: CFTypeRef?
        guard SecItemCopyMatching(query as CFDictionary, &out) == errSecSuccess, let data = out as? Data else { return nil }
        return String(data: data, encoding: .utf8)
    }

    static func passwordKey(_ id: UUID) -> String { "password.\(id.uuidString)" }
    static func deviceTokenKey(_ id: UUID) -> String { "deviceToken.\(id.uuidString)" }
    static func sshPasswordKey(_ id: UUID) -> String { "sshPassword.\(id.uuidString)" }
}
